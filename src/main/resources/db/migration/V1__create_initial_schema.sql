
-- =====================================================
-- SMART MUSHROOM - INITIAL DATABASE SCHEMA
-- Flyway Migration V1
-- PostgreSQL
-- =====================================================

-- 1. USERS
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    phone VARCHAR(20),
    role VARCHAR(30) NOT NULL
        CHECK (role IN ('ADMIN', 'OPERATOR', 'CUSTOMER')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. ROOMS
CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code VARCHAR(50) NOT NULL UNIQUE,
    room_name VARCHAR(150) NOT NULL,
    description TEXT,
    location VARCHAR(255),
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'MAINTENANCE', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. TRAYS
CREATE TABLE trays (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id),
    tray_code VARCHAR(50) NOT NULL UNIQUE,
    tray_name VARCHAR(150),
    mushroom_type VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE'
        CHECK (status IN (
            'AVAILABLE', 'RENTED', 'CULTIVATING',
            'HARVESTING', 'COMPLETED', 'MAINTENANCE'
        )),
    started_at TIMESTAMPTZ,
    expected_harvest_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. RENTAL PACKAGES
CREATE TABLE rental_packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_name VARCHAR(150) NOT NULL,
    description TEXT,
    duration_days INTEGER NOT NULL CHECK (duration_days > 0),
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. RENTALS
CREATE TABLE rentals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES users(id),
    tray_id BIGINT NOT NULL REFERENCES trays(id),
    package_id BIGINT NOT NULL REFERENCES rental_packages(id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN (
            'PENDING', 'CONFIRMED', 'ACTIVE',
            'COMPLETED', 'CANCELLED'
        )),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date >= start_date)
);

-- 6. TRANSACTIONS
CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id BIGINT NOT NULL REFERENCES rentals(id),
    amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    payment_method VARCHAR(30) NOT NULL
        CHECK (payment_method IN ('CASH', 'BANK_TRANSFER', 'ONLINE')),
    transaction_code VARCHAR(100) UNIQUE,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REFUNDED')),
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 7. DEVICES
CREATE TABLE devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_code VARCHAR(100) NOT NULL UNIQUE,
    device_name VARCHAR(150) NOT NULL,
    device_type VARCHAR(50) NOT NULL,
    room_id BIGINT REFERENCES rooms(id),
    tray_id BIGINT REFERENCES trays(id),
    status VARCHAR(30) NOT NULL DEFAULT 'ONLINE'
        CHECK (status IN ('ONLINE', 'OFFLINE', 'MAINTENANCE')),
    last_seen_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (room_id IS NOT NULL OR tray_id IS NOT NULL)
);

-- 8. SENSOR READINGS
CREATE TABLE sensor_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES devices(id),
    temperature NUMERIC(6,2),
    humidity NUMERIC(6,2),
    co2_level NUMERIC(10,2),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 9. THRESHOLDS
CREATE TABLE thresholds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT REFERENCES rooms(id),
    mushroom_type VARCHAR(100),
    min_temperature NUMERIC(6,2),
    max_temperature NUMERIC(6,2),
    min_humidity NUMERIC(6,2),
    max_humidity NUMERIC(6,2),
    min_co2 NUMERIC(10,2),
    max_co2 NUMERIC(10,2),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CHECK (
        min_temperature IS NULL OR max_temperature IS NULL
        OR min_temperature <= max_temperature
    ),

    CHECK (
        min_humidity IS NULL OR max_humidity IS NULL
        OR min_humidity <= max_humidity
    ),

    CHECK (
        min_co2 IS NULL OR max_co2 IS NULL
        OR min_co2 <= max_co2
    )
);

-- 10. ALERTS
CREATE TABLE alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT REFERENCES rooms(id),
    tray_id BIGINT REFERENCES trays(id),
    device_id BIGINT REFERENCES devices(id),
    alert_type VARCHAR(50) NOT NULL,
    message TEXT NOT NULL,
    severity VARCHAR(20) NOT NULL DEFAULT 'WARNING'
        CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'RESOLVED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ
);

-- 11. NOTIFICATIONS
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    notification_type VARCHAR(50),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 12. TRAY PROGRESS LOGS
CREATE TABLE tray_progress_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tray_id BIGINT NOT NULL REFERENCES trays(id),
    created_by BIGINT REFERENCES users(id),
    growth_stage VARCHAR(100) NOT NULL,
    description TEXT,
    image_url TEXT,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 13. HARVEST SCHEDULES
CREATE TABLE harvest_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tray_id BIGINT NOT NULL REFERENCES trays(id),
    rental_id BIGINT REFERENCES rentals(id),
    scheduled_date DATE NOT NULL,
    actual_harvest_date DATE,
    estimated_yield_kg NUMERIC(10,2),
    actual_yield_kg NUMERIC(10,2),
    status VARCHAR(30) NOT NULL DEFAULT 'PLANNED'
        CHECK (status IN ('PLANNED', 'HARVESTED', 'CANCELLED')),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 14. DELIVERY REQUESTS
CREATE TABLE delivery_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id BIGINT NOT NULL REFERENCES rentals(id),
    customer_id BIGINT NOT NULL REFERENCES users(id),
    request_type VARCHAR(30) NOT NULL
        CHECK (request_type IN ('PICKUP', 'DELIVERY')),
    delivery_address TEXT,
    requested_date DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN (
            'PENDING', 'APPROVED', 'PROCESSING',
            'COMPLETED', 'CANCELLED'
        )),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =====================================================
-- INDEXES
-- =====================================================

CREATE INDEX idx_trays_room_id
    ON trays(room_id);

CREATE INDEX idx_rentals_customer_id
    ON rentals(customer_id);

CREATE INDEX idx_rentals_tray_id
    ON rentals(tray_id);

CREATE INDEX idx_transactions_rental_id
    ON transactions(rental_id);

CREATE INDEX idx_devices_room_id
    ON devices(room_id);

CREATE INDEX idx_sensor_readings_device_time
    ON sensor_readings(device_id, recorded_at DESC);

CREATE INDEX idx_alerts_status
    ON alerts(status);

CREATE INDEX idx_notifications_user_id
    ON notifications(user_id);

CREATE INDEX idx_progress_logs_tray_id
    ON tray_progress_logs(tray_id);

CREATE INDEX idx_harvest_schedules_tray_id
    ON harvest_schedules(tray_id);

CREATE INDEX idx_delivery_requests_customer_id
    ON delivery_requests(customer_id);
